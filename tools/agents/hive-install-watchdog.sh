#!/bin/bash
# Usage: hive-install-watchdog.sh [account]       (install.sh runs it; safe to re-run, and to run by hand on any machine)
# Generates this machine's watchdog launchers for this install, under ~/.claude/hive/ (outside the repo, per machine and
# per account; nothing in the repo or anywhere else is touched, no daemon is started):
#   hive-watchdog-<repo>-<account>.sh      thin wrapper: sets the account and PATH, runs this checkout's hive-watchdog.sh
#                                          (so a later `git pull` + install refresh updates the logic with no regeneration)
#   hive-start-<repo>-<account>.command    login starter: starts that wrapper in the screen hive-watchdog-<repo>-<account>
#                                          unless it already runs. macOS: the Terminal-from-launchd approach (background jobs
#                                          cannot read ~/Desktop); elsewhere run it from your login script / systemd unit.
# On Windows (Git Bash) it registers the scheduled tasks instead (windows/hive-install-task.ps1).
# Account: the argument, else HIVE_ACCOUNT, else `gh api user`. Prints the one command that starts the watchdog now.
# What the watchdog starts, and for which repos, is decided on every tick from the studio stack: see hive-watchdog.sh.
HIVE_DIR=$(cd "$(dirname "$0")" && pwd); ROOT=$(cd "$HIVE_DIR/../.." && pwd)
acct=${1:-${HIVE_ACCOUNT:-}}; [ -n "$acct" ] || acct=$(gh api user -q .login 2>/dev/null)
[ -n "$acct" ] || { echo "watchdog: no account (pass one, or set HIVE_ACCOUNT, or log in with gh); not generated" >&2; exit 1; }
name=$(sed -n 's/^REPO=//p' "$ROOT/hive.conf" 2>/dev/null | head -n 1 | tr -d '"'"'"'\r'); name=${name#*/}; name=${name:-${ROOT##*/}}
# Windows (Git Bash): the watchdog is a Task Scheduler task running windows/hive-watchdog.ps1 every minute, registered by
# windows/hive-install-task.ps1 (also the always-on session and msg/voice watchers, keep-awake). Nothing is started here.
case ${HIVE_WATCHDOG_OS:-$(uname -s)} in MINGW*|MSYS*|CYGWIN*)
  powershell.exe -NoProfile -ExecutionPolicy Bypass -File "$(cygpath -w "$HIVE_DIR/windows/hive-install-task.ps1" 2>/dev/null || echo "$HIVE_DIR/windows/hive-install-task.ps1")" -Account "$acct" \
    && echo "  registered the Windows watchdog tasks for $acct (hive AT watchdog / watchers / session)" || { echo "watchdog: hive-install-task.ps1 failed; run it by hand" >&2; exit 1; }
  exit 0;;
esac
D=${HIVE_WATCHDOG_DIR:-$HOME/.claude/hive}; mkdir -p "$D" || exit 1
W=$D/hive-watchdog-$name-$acct.sh; S=$D/hive-start-$name-$acct.command
q() { printf %q "$1"; }
cat > "$W" <<WRAP
#!/bin/bash
# Generated by $(q "$HIVE_DIR/hive-install-watchdog.sh") for $acct on this machine. Do not edit; re-run the installer.
# Every minute: starts the hive daemons the studio stack calls for (always-on session, msg, voice, one automerger per
# stacked repo on the triagemaster's machine). Zero tokens. Logic: tools/agents/hive-watchdog.sh in the checkout below.
export HIVE_ACCOUNT=$(q "$acct") PATH="\$HOME/.local/bin:/usr/local/bin:/opt/homebrew/bin:\$PATH"
cd $(q "$ROOT") || exit 1
exec bash tools/agents/hive-watchdog.sh "\$@"
WRAP
cat > "$S" <<START
#!/bin/bash
# Generated by $(q "$HIVE_DIR/hive-install-watchdog.sh"). Login starter: runs the watchdog in a detached screen if it isn't up.
export HIVE_ACCOUNT=$(q "$acct") PATH="\$HOME/.local/bin:/usr/local/bin:/opt/homebrew/bin:\$PATH"
screen -ls | grep -Eq "[0-9]\.hive-watchdog-$name-$acct[[:space:]]" || screen -dmS hive-watchdog-$name-$acct bash $(q "$W")
echo "\$(date '+%m-%d %I:%M %p') login start" >> "\$HOME/.claude/hive/login-start.log"
[ "\$(uname -s)" = Darwin ] && osascript -e 'tell application "Terminal" to close (every window whose name contains "hive-start-$name-$acct")' >/dev/null 2>&1 &
exit 0
START
chmod +x "$W" "$S"
echo "  generated the watchdog for $acct: $W (login starter: $S)"
echo "  start it now:  bash $S      (it then starts the always-on session, msg, voice and one automerger per stacked repo)"
